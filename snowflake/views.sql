-- Analytics views (docs/program-discovery-pipeline.md, Section 16).
-- Run as PROGRAM_PIPELINE_LOADER after the first sync. All views are aggregates:
-- no user IDs, ZIP codes or locations ever reach Snowflake.

USE ROLE PROGRAM_PIPELINE_LOADER;
USE WAREHOUSE PROGRAM_PIPELINE_WH;

-- Jurisdictions by level and coverage status.
CREATE OR REPLACE VIEW PROGRAM_PIPELINE.ANALYTICS.COVERAGE_SUMMARY AS
SELECT j.LEVEL,
       c.STATUS,
       COUNT(*) AS JURISDICTIONS,
       SUM(c.PUBLISHED_PROGRAM_COUNT) AS PUBLISHED_PROGRAMS,
       SUM(c.USER_COUNT) AS USERS
FROM PROGRAM_PIPELINE.RAW.JURISDICTION_COVERAGE c
JOIN PROGRAM_PIPELINE.RAW.JURISDICTIONS j ON j.ID = c.JURISDICTION_ID
GROUP BY 1, 2;

-- Searches per day.
CREATE OR REPLACE VIEW PROGRAM_PIPELINE.ANALYTICS.SERPAPI_USAGE_DAILY AS
SELECT DATE_TRUNC('day', r.CREATED_AT) AS DAY,
       j.TRIGGERED_BY,
       COUNT(*) AS SEARCHES,
       COUNT_IF(r.ORGANIC_COUNT = 0) AS EMPTY_SEARCHES
FROM PROGRAM_PIPELINE.RAW.SERPAPI_REQUESTS r
LEFT JOIN PROGRAM_PIPELINE.RAW.INGESTION_JOBS j ON j.ID = r.JOB_ID
GROUP BY 1, 2;

-- Published programs per search, per jurisdiction.
CREATE OR REPLACE VIEW PROGRAM_PIPELINE.ANALYTICS.DISCOVERY_YIELD AS
WITH searches AS (
  SELECT JURISDICTION_ID, SUM(SEARCHES_USED) AS SEARCHES, COUNT(*) AS JOBS
  FROM PROGRAM_PIPELINE.RAW.INGESTION_JOBS
  WHERE STATUS = 'succeeded'
  GROUP BY 1
), published AS (
  SELECT JURISDICTION_ID, COUNT(*) AS PUBLISHED_PROGRAMS
  FROM PROGRAM_PIPELINE.RAW.PROGRAMS
  WHERE REVIEW_STATUS = 'published' AND STATUS = 'active' AND ORIGIN = 'discovery'
  GROUP BY 1
)
SELECT j.ID AS JURISDICTION_ID,
       j.DISPLAY_NAME,
       j.LEVEL,
       s.JOBS,
       s.SEARCHES,
       COALESCE(p.PUBLISHED_PROGRAMS, 0) AS PUBLISHED_PROGRAMS,
       COALESCE(p.PUBLISHED_PROGRAMS, 0) / NULLIF(s.SEARCHES, 0) AS PROGRAMS_PER_SEARCH
FROM searches s
JOIN PROGRAM_PIPELINE.RAW.JURISDICTIONS j ON j.ID = s.JURISDICTION_ID
LEFT JOIN published p ON p.JURISDICTION_ID = s.JURISDICTION_ID;

-- needs_review programs by age.
CREATE OR REPLACE VIEW PROGRAM_PIPELINE.ANALYTICS.REVIEW_BACKLOG AS
SELECT CASE
         WHEN DATEDIFF('day', FIRST_SEEN_AT, CURRENT_TIMESTAMP()) < 7 THEN '0-6 days'
         WHEN DATEDIFF('day', FIRST_SEEN_AT, CURRENT_TIMESTAMP()) < 30 THEN '7-29 days'
         WHEN DATEDIFF('day', FIRST_SEEN_AT, CURRENT_TIMESTAMP()) < 90 THEN '30-89 days'
         ELSE '90+ days'
       END AS AGE,
       ORIGIN,
       AUDIENCE,
       COUNT(*) AS PROGRAMS,
       MIN(FIRST_SEEN_AT) AS OLDEST
FROM PROGRAM_PIPELINE.RAW.PROGRAMS
WHERE REVIEW_STATUS = 'needs_review'
GROUP BY 1, 2, 3;

-- Sponsor demo views (aggregate only) ---------------------------------------

-- What help exists, by category and level of government (programs people can see).
CREATE OR REPLACE VIEW PROGRAM_PIPELINE.ANALYTICS.PROGRAMS_BY_CATEGORY AS
SELECT COALESCE(c.VALUE::VARCHAR, 'uncategorized') AS CATEGORY,
       j.LEVEL,
       COUNT(DISTINCT p.ID) AS PROGRAMS
FROM PROGRAM_PIPELINE.RAW.PROGRAMS p
JOIN PROGRAM_PIPELINE.RAW.JURISDICTIONS j ON j.ID = p.JURISDICTION_ID,
     LATERAL FLATTEN(INPUT => p.CATEGORIES, OUTER => TRUE) c
WHERE p.REVIEW_STATUS = 'published' AND p.STATUS = 'active' AND p.AUDIENCE = 'individual'
GROUP BY 1, 2;

-- State, county and city programs people can see, rolled up to the state, next to
-- how many people Equa serves there (from coverage counts, never per-user rows).
CREATE OR REPLACE VIEW PROGRAM_PIPELINE.ANALYTICS.PROGRAMS_BY_STATE AS
WITH programs AS (
  SELECT j.STATE_CODE,
         COUNT_IF(j.LEVEL = 'state') AS STATE_PROGRAMS,
         COUNT_IF(j.LEVEL IN ('county', 'city')) AS LOCAL_PROGRAMS
  FROM PROGRAM_PIPELINE.RAW.PROGRAMS p
  JOIN PROGRAM_PIPELINE.RAW.JURISDICTIONS j ON j.ID = p.JURISDICTION_ID
  WHERE p.REVIEW_STATUS = 'published' AND p.STATUS = 'active' AND p.AUDIENCE = 'individual'
    AND j.STATE_CODE IS NOT NULL
  GROUP BY 1
), people AS (
  SELECT j.STATE_CODE, c.USER_COUNT AS USERS, c.STATUS AS STATE_COVERAGE
  FROM PROGRAM_PIPELINE.RAW.JURISDICTION_COVERAGE c
  JOIN PROGRAM_PIPELINE.RAW.JURISDICTIONS j ON j.ID = c.JURISDICTION_ID
  WHERE j.LEVEL = 'state'
)
SELECT pe.STATE_CODE,
       pe.STATE_COVERAGE,
       pe.USERS,
       COALESCE(pr.STATE_PROGRAMS, 0) AS STATE_PROGRAMS,
       COALESCE(pr.LOCAL_PROGRAMS, 0) AS LOCAL_PROGRAMS
FROM people pe
LEFT JOIN programs pr ON pr.STATE_CODE = pe.STATE_CODE;

-- Federal programs people can see, by administering agency.
CREATE OR REPLACE VIEW PROGRAM_PIPELINE.ANALYTICS.FEDERAL_PROGRAMS_BY_AGENCY AS
SELECT COALESCE(p.ADMINISTERING_AGENCY, 'Unknown') AS AGENCY,
       COUNT(*) AS PROGRAMS
FROM PROGRAM_PIPELINE.RAW.PROGRAMS p
JOIN PROGRAM_PIPELINE.RAW.JURISDICTIONS j ON j.ID = p.JURISDICTION_ID
WHERE j.LEVEL = 'federal'
  AND p.REVIEW_STATUS = 'published' AND p.STATUS = 'active' AND p.AUDIENCE = 'individual'
GROUP BY 1;
